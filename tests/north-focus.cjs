/* eslint-disable @typescript-eslint/no-require-imports -- Standalone Node test runner. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const exportsObject={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/north.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:exportsObject,Date});
const {createArea,weekKey,shiftDay,dailySelection,areaStreak,weeklyConsistency,missedAdvice,capacity,allocation}=exportsObject;
assert.equal(weekKey('2026-09-06'),'2026-08-31');
assert.equal(shiftDay('2026-12-31',1),'2027-01-01');
const area={...createArea('math','math'),goal:'Sınava hazırlan',weeklyMinutes:300};
const task={id:'t1',areaId:'math',title:'5 problem',goal:'5 doğru çözüm',minutes:50,intensity:'high',mandatory:true,status:'pending',date:'',deadline:'',week:'2026-08-31'};
const state={version:1,areas:[area],tasks:[task],activities:[],events:[],energy:{date:'',level:'normal'},weeklyHours:5,mode:'normal',customMode:'',protection:[]};
assert.equal(dailySelection(state,'2026-09-05').length,1);
assert.equal(dailySelection({...state,weeklyHours:0},'2026-09-05').length,0);
assert.equal(dailySelection({...state,areas:[{...area,goal:''}]},'2026-09-05').length,0);
assert.equal(dailySelection({...state,areas:[{...area,archived:true}]},'2026-09-05').length,0);
assert.equal(dailySelection({...state,areas:[{...area,status:'paused'}]},'2026-09-05').length,0);
assert.equal(allocation({...state,areas:[{...area,status:'paused'}]},{...area,status:'paused'}),0);
assert.equal(dailySelection({...state,tasks:[{...task,date:'2026-09-04'}]},'2026-09-05').length,0);
assert.equal(dailySelection({...state,tasks:[{...task,date:'2026-09-06'}]},'2026-09-05').length,0);
assert.equal(capacity({...state,mode:'exam'}),210);
assert.equal(dailySelection({...state,tasks:[task,{...task,id:'t2'},{...task,id:'t3'}],activities:[{taskId:'t1',date:'2026-09-05',minutes:0},{taskId:'t2',date:'2026-09-05',minutes:0}]},'2026-09-05').length,0);
assert.equal(missedAdvice({...task,mandatory:false}).action,'cancel');
assert.equal(missedAdvice({...task,minutes:80}).action,'reduce');
const activity=(date,minutes=10)=>({id:date,taskId:'t1',areaId:'math',date,minutes,outcome:'done'});
const streakState={...state,activities:[activity('2026-09-03'),activity('2026-09-05')],protection:[{areaId:'math',date:'2026-09-04',kind:'rest'}]};
assert.equal(areaStreak(streakState,area,'2026-09-05'),2);
assert.equal(areaStreak({...streakState,protection:[]},area,'2026-09-05'),1);
assert.equal(areaStreak({...state,activities:[activity('2026-09-05',0)]},area,'2026-09-05'),0);
assert.equal(weeklyConsistency(streakState,area,'2026-09-05'),40);
assert.equal(dailySelection({...state,protection:[{areaId:'math',date:'2026-09-05',kind:'rest'}]},'2026-09-05').length,0);
console.log('North focus checks passed: local dates, capacity, inactive/goal guards, missed tasks, rest protection, real-activity streaks.');
